-- ============================================================================
-- 14. ШАБЛОН ОФФЕРА: ИМЕНА ПОДСТАНОВОК
--
-- Шаблон в базе просил {{probation_months}} и {{first_month_reality}}, а
-- приложение подставляет {{probation}} и {{first_month}}. Подстановка, для
-- которой значения нет, остаётся в тексте как «⟨probation_months не
-- заполнено⟩» — и это ушло бы кандидату в предложении о работе.
--
-- Там же лишний знак рубля: сумму форматирует приложение, и «₽» в ней уже
-- есть. В тексте получалось «158 000 ₽ ₽».
--
-- Правится текст, а не код: имена подстановок задаёт тот, кто рисует оффер,
-- и менять их ради базы неправильно. Перечень доступных полей — в
-- app/src/pages/Offers.tsx, функция NewOfferModal.
-- ============================================================================

update public.offer_templates
set body_md = replace(
      replace(
        replace(body_md, '{{probation_months}}', '{{probation}}'),
        '{{first_month_reality}}', '{{first_month}}'),
      '**{{salary}} ₽**', '**{{salary}}**')
where body_md like '%{{probation_months}}%'
   or body_md like '%{{first_month_reality}}%'
   or body_md like '%{{salary}} ₽%';
