-- ============================================================================
-- 13. КТО ИМЕЕТ ПРАВО ЗВАТЬ СЛУЖЕБНЫЕ ФУНКЦИИ
--
-- Ошибка предыдущей миграции. Четыре функции обслуживания были созданы без
-- единого слова о правах — а PostgreSQL в таком случае раздаёт право
-- выполнения всем подряд. PostgREST показывает такие функции наружу, и
-- позвать их мог любой, у кого есть публикуемый ключ, — а он лежит в
-- браузерном бандле, то есть у всех.
--
-- Это не теория: проверил на живой базе анонимным ключом, purge_expired_
-- candidates ответила «0». То есть выполнилась. Сегодня удалять было нечего,
-- потому что сроки хранения ещё не вышли. Через год тот же вызов удалил бы
-- людей по чужой команде и в чужой момент, а anonymize_candidate стёрла бы
-- переписку и документы конкретного человека по одному его id.
--
-- Функции остаются: они нужны планировщику. Планировщик ходит под ролью
-- postgres, и права ему не нужны — он владелец. Убираем только тех, кто
-- приходит снаружи.
--
-- Внутренняя проверка на суперпользователя (она есть у drop_demo_data) для
-- остальных трёх не годится: их зовёт ночной планировщик, у которого нет
-- ни сессии, ни auth.uid(). Право на вызов и проверка вошедшего — разные
-- механизмы, и здесь нужен первый.
-- ============================================================================

revoke all on function public.anonymize_candidate(uuid, text)
  from public, anon, authenticated;

revoke all on function public.process_deletion_requests()
  from public, anon, authenticated;

revoke all on function public.purge_expired_candidates()
  from public, anon, authenticated;

revoke all on function public.drop_demo_data()
  from public, anon, authenticated;

