-- ============================================================================
-- 16. КАНДИДАТ ВИДИТ СВОЙ ПУТЬ ПО ВОРОНКЕ (фишка 42)
--
-- Экран «Мой статус» рисует кандидату весь путь: где он сейчас, что было
-- до и что будет дальше. Для этого ему нужны названия и порядок этапов.
-- А политика на воронках пускала только is_staff() — кандидат получал
-- пустой список и видел карточку без единого этапа.
--
-- Заметить это было трудно: в Телеграме то же самое работает. Бот ходит
-- под служебным ключом, RLS его не касается, и /status честно называет
-- этап по имени. Ровно то же самое в браузере молча не работало.
--
-- Названия этапов не тайна: мы и так сообщаем их кандидату ботом, письмом
-- и в самом интерфейсе. Тайна — кто ещё на каком этапе, а это уже другая
-- таблица (applications), и там политика не меняется.
-- ============================================================================

create policy "pipelines: кандидат видит воронку своего отклика"
  on public.pipelines
  for select using (public.my_candidate_id() is not null);

create policy "stages: кандидат видит этапы своего пути"
  on public.pipeline_stages
  for select using (public.my_candidate_id() is not null);
